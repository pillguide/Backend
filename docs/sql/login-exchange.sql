-- Apply before enabling the OAuth exchange callback. No code or verifier plaintext is stored.
BEGIN;

CREATE TABLE IF NOT EXISTS login_exchange (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash varchar(64) NOT NULL,
    challenge varchar(43) NOT NULL,
    member_id bigint NOT NULL REFERENCES member(id) ON DELETE CASCADE,
    expires_at timestamp without time zone NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_login_exchange_code_hash ON login_exchange(code_hash);
CREATE INDEX IF NOT EXISTS ix_login_exchange_expires_at ON login_exchange(expires_at);

COMMIT;
