-- P2 reference and scan state. PostgreSQL 17; run after the read-only DEV
-- preflight. This script preserves existing drug, drug_info and scan rows.
-- It is repeatable and stops on duplicate identities instead of deleting data.
BEGIN;

-- The current DEV schema uses drug.drug_id, drug_info.info_id,
-- scan_session.id, scan_drug.id, scan_drug.drug_drug_id and member.id.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM drug GROUP BY code HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'drug.code duplicates require review';
    END IF;
    IF EXISTS (SELECT 1 FROM drug_info GROUP BY drug_id HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'drug_info.drug_id duplicates require review';
    END IF;
END $$;

ALTER TABLE drug ADD COLUMN IF NOT EXISTS model_name varchar(255);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS product_code varchar(255);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS classification_code varchar(255);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS classification_name varchar(255);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS ingredient_display text;
ALTER TABLE drug ADD COLUMN IF NOT EXISTS authorization_status varchar(255);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS info_status varchar(255);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS source_as_of date;
ALTER TABLE drug ADD COLUMN IF NOT EXISTS representative_image_key varchar(1024);
ALTER TABLE drug ADD COLUMN IF NOT EXISTS representative_image_hash varchar(64);

ALTER TABLE drug_info ADD COLUMN IF NOT EXISTS selected_sources_json text;
ALTER TABLE drug_info ADD COLUMN IF NOT EXISTS provenance_status varchar(255);
ALTER TABLE drug_info ADD COLUMN IF NOT EXISTS source_fetched_at timestamp without time zone;

ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS request_id uuid;
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS request_hash varchar(64);
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS image_width integer;
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS image_height integer;
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS model_sha256 varchar(64);
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS mapping_sha256 varchar(64);
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS reference_version varchar(255);
ALTER TABLE scan_session ADD COLUMN IF NOT EXISTS interaction_snapshot text;

ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS detection_index integer;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS confidence double precision;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS bbox_x1 double precision;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS bbox_y1 double precision;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS bbox_x2 double precision;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS bbox_y2 double precision;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS recognition_may_be_degraded boolean;
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS name_snapshot varchar(255);
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS info_status_snapshot varchar(255);
ALTER TABLE scan_drug ADD COLUMN IF NOT EXISTS authorization_status_snapshot varchar(255);

-- Recheck after adding nullable columns so the first run works on the old schema.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM scan_session
        WHERE request_id IS NOT NULL
        GROUP BY member_id, request_id HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'scan_session member/request duplicates require review';
    END IF;
    IF EXISTS (
        SELECT 1 FROM scan_drug
        WHERE detection_index IS NOT NULL
        GROUP BY scan_session_id, detection_index HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'scan_drug session/index duplicates require review';
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_scan_session_member_request'
                   AND conrelid = 'scan_session'::regclass) THEN
        ALTER TABLE scan_session ADD CONSTRAINT uk_scan_session_member_request
            UNIQUE (member_id, request_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_scan_drug_session_index'
                   AND conrelid = 'scan_drug'::regclass) THEN
        ALTER TABLE scan_drug ADD CONSTRAINT uk_scan_drug_session_index
            UNIQUE (scan_session_id, detection_index);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS drug_interaction (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    low_drug_id bigint NOT NULL REFERENCES drug(drug_id),
    high_drug_id bigint NOT NULL REFERENCES drug(drug_id),
    evidence_json text NOT NULL,
    official_reason text,
    reviewed_summary text,
    source_hash varchar(64) NOT NULL,
    summary_source_hash varchar(64),
    source_as_of date NOT NULL,
    reference_version varchar(255) NOT NULL,
    CONSTRAINT uk_drug_interaction_pair UNIQUE (low_drug_id, high_drug_id),
    CONSTRAINT ck_drug_interaction_order CHECK (low_drug_id < high_drug_id)
);

CREATE TABLE IF NOT EXISTS member_drug (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id bigint NOT NULL REFERENCES member(id),
    drug_id bigint NOT NULL REFERENCES drug(drug_id),
    first_registered_at timestamp without time zone NOT NULL,
    CONSTRAINT uk_member_drug_member_drug UNIQUE (member_id, drug_id)
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM drug_interaction
        GROUP BY low_drug_id, high_drug_id HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'drug_interaction pair duplicates require review';
    END IF;
    IF EXISTS (
        SELECT 1 FROM drug_interaction WHERE low_drug_id >= high_drug_id
    ) THEN
        RAISE EXCEPTION 'drug_interaction ordering errors require review';
    END IF;
    IF EXISTS (
        SELECT 1 FROM member_drug
        GROUP BY member_id, drug_id HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'member_drug pair duplicates require review';
    END IF;
END $$;

-- CREATE TABLE IF NOT EXISTS may have reused a pre-existing table without
-- the order check. Add it while preserving rows.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'ck_drug_interaction_order'
                   AND conrelid = 'drug_interaction'::regclass) THEN
        ALTER TABLE drug_interaction ADD CONSTRAINT ck_drug_interaction_order
            CHECK (low_drug_id < high_drug_id);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_drug_interaction_pair'
                   AND conrelid = 'drug_interaction'::regclass) THEN
        ALTER TABLE drug_interaction ADD CONSTRAINT uk_drug_interaction_pair
            UNIQUE (low_drug_id, high_drug_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uk_member_drug_member_drug'
                   AND conrelid = 'member_drug'::regclass) THEN
        ALTER TABLE member_drug ADD CONSTRAINT uk_member_drug_member_drug
            UNIQUE (member_id, drug_id);
    END IF;
END $$;

COMMIT;
